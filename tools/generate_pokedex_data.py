#!/usr/bin/env python3
"""Generate byte-audited JP Pokédex text and entry headers.

The generator consumes only the manifest produced by audit_pokedex_text.  That
manifest proves every Japanese description and fixed category string can be
encoded by tools/preproc/preproc without changing its ROM bytes, and proves
that each entry points at its corresponding description.  Upstream is used
only for stable source names and National Dex order; JP text and numeric data
always come from the Japanese ROM.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

import audit_pokedex_text


ROOT = Path(__file__).resolve().parents[1]
US_ENTRIES_PATH = ROOT.parent / "pokeemerald" / "src" / "data" / "pokemon" / "pokedex_entries.h"
DEFAULT_TEXT_OUTPUT = ROOT / "src" / "data" / "pokemon" / "pokedex_text.h"
DEFAULT_ENTRIES_OUTPUT = ROOT / "src" / "data" / "pokemon" / "pokedex_entries.h"
DEX_LABEL_RE = re.compile(r"^\s*\[(NATIONAL_DEX_[A-Z0-9_]+)\]\s*=", re.MULTILINE)


def dex_labels() -> list[str]:
    labels = DEX_LABEL_RE.findall(US_ENTRIES_PATH.read_text(encoding="utf-8"))
    if not labels:
        raise ValueError(f"no National Dex labels found in {US_ENTRIES_PATH}")
    if len(labels) != len(set(labels)):
        raise ValueError("duplicate National Dex labels in upstream entries")
    return labels


def quoted_chunks(source: str) -> list[str]:
    """Wrap only after the JP text engine's explicit line/page controls."""
    chunks: list[str] = []
    current: list[str] = []
    pos = 0
    while pos < len(source):
        if source[pos] == "\\" and pos + 1 < len(source) and source[pos + 1] in "nlp":
            current.append(source[pos : pos + 2])
            chunks.append("".join(current))
            current = []
            pos += 2
            continue
        current.append(source[pos])
        pos += 1
    if current or not chunks:
        chunks.append("".join(current))
    return chunks


def render_string_definition(label: str, source: str, data_macro: str) -> str:
    if not source.endswith("$"):
        raise ValueError(f"text {label} is missing EOS")
    chunks = quoted_chunks(source[:-1])
    if len(chunks) == 1:
        return f"const u8 {label}[] {data_macro} = _(\"{chunks[0]}\");"
    lines = [f"const u8 {label}[] {data_macro} = _("]
    lines.extend(f"    \"{chunk}\"" for chunk in chunks[:-1])
    lines.append(f"    \"{chunks[-1]}\");")
    return "\n".join(lines)


def render_text_header(manifest: dict[str, object]) -> str:
    lines = [
        "// Generated by tools/generate_pokedex_data.py from the verified JP ROM manifest.",
        "// Keep this include in src/pokedex.c so its final owner follows pokeemerald.",
        "",
        "#define POKEDEX_TEXT_DATA __attribute__((section(\".rodata.pokedex_text\"), aligned(1)))",
        "",
        "// 0x08539C50 is the byte-exact empty description used before gDummyPokedexText.",
        "const u8 gText_EmptyPokedexDescription[] POKEDEX_TEXT_DATA = _(\"\");",
        "",
    ]
    for entry in manifest["entries"]:
        entry = dict(entry)
        lines.append(f"// {entry['rom_offset']}")
        lines.append(render_string_definition(str(entry["label"]), str(entry["source"]), "POKEDEX_TEXT_DATA"))
        lines.append("")
    lines.append("#undef POKEDEX_TEXT_DATA")
    lines.append("")
    return "\n".join(lines)


def render_entries_header(manifest: dict[str, object]) -> str:
    dex = dex_labels()
    records = list(manifest["entry_records"])
    text_entries = list(manifest["entries"])
    if len(dex) != len(records) or len(records) != len(text_entries):
        raise ValueError(
            f"US Dex labels={len(dex)}, JP records={len(records)}, JP texts={len(text_entries)}"
        )

    lines = [
        "// Generated by tools/generate_pokedex_data.py from the verified JP ROM manifest.",
        "// JP retains its original compact PokedexEntry layout; do not copy US bytes.",
        "",
        "#define POKEDEX_ENTRIES_DATA __attribute__((section(\".rodata.pokedex_entries\")))",
        "",
        "const struct PokedexEntry gPokedexEntries[] POKEDEX_ENTRIES_DATA =",
        "{",
    ]
    for dex_label, record, text in zip(dex, records, text_entries, strict=True):
        record = dict(record)
        text = dict(text)
        lines.extend(
            [
                f"    // {record['rom_offset']}",
                f"    [{dex_label}] =",
                "    {",
                f"        .categoryName = __(\"{record['category']}\"),",
                f"        .height = {record['height']},",
                f"        .weight = {record['weight']},",
                f"        .description = {text['label']},",
                f"        .unused = {record['unused']},",
                f"        .pokemonScale = {record['pokemon_scale']},",
                f"        .pokemonOffset = {record['pokemon_offset']},",
                f"        .trainerScale = {record['trainer_scale']},",
                f"        .trainerOffset = {record['trainer_offset']},",
                "    },",
                "",
            ]
        )
    lines.extend(["};", "", "#undef POKEDEX_ENTRIES_DATA", ""])
    return "\n".join(lines)


def write_if_changed(path: Path, content: str) -> bool:
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return True


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--text-output", type=Path, default=DEFAULT_TEXT_OUTPUT)
    parser.add_argument("--entries-output", type=Path, default=DEFAULT_ENTRIES_OUTPUT)
    parser.add_argument("--check", action="store_true", help="fail instead of rewriting stale generated files")
    args = parser.parse_args()

    manifest = audit_pokedex_text.report()
    text = render_text_header(manifest)
    entries = render_entries_header(manifest)
    outputs = ((args.text_output, text), (args.entries_output, entries))
    stale = [path for path, content in outputs if not path.exists() or path.read_text(encoding="utf-8") != content]
    if args.check:
        if stale:
            raise SystemExit("stale generated Pokédex data: " + ", ".join(map(str, stale)))
        print("Pokédex data headers are current")
        return
    for path, content in outputs:
        changed = write_if_changed(path, content)
        print(f"{'wrote' if changed else 'unchanged'} {path}")


if __name__ == "__main__":
    main()
