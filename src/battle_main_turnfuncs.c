#include "global.h"

// JP byte-exact turn/battle-script command dispatch. The JP ROM shares a
// stack frame between RunBattleScriptCommands (0x0803D45C) and
// RunTurnActionsFunctions (0x0803D488, no prologue), with the literal
// pools interleaved inside the combined body, so the whole 0xA8-byte
// region is one naked asm function and RunTurnActionsFunctions is an
// ld alias to RunBattleScriptCommands + 0x2C.

__attribute__((naked)) void RunBattleScriptCommands(void)
{
    __asm__(".syntax unified\n\t"
        ".code 16\n\t"
        "push {r4, r5, r6, lr}\n\t"
        "ldr r6, _0803D4B0\n\t"
        "ldrb r0, [r6]\n\t"
        "ldr r2, _0803D4B4\n\t"
        "cmp r0, #0\n\t"
        "beq _0803D46C\n\t"
        "movs r0, #0xc\n\t"
        "strb r0, [r2]\n\t"
        "_0803D46C:\n\t"
        "ldr r5, _0803D4B8\n\t"
        "ldr r0, [r5]\n\t"
        "adds r0, #0x4b\n\t"
        "ldr r4, _0803D4BC\n\t"
        "ldrb r1, [r4]\n\t"
        "strb r1, [r0]\n\t"
        "ldr r1, _0803D4C0\n\t"
        "ldrb r0, [r2]\n\t"
        "lsls r0, r0, #2\n\t"
        "adds r0, r0, r1\n\t"
        "ldr r0, [r0]\n\t"
        "bl _call_via_r0\n\t"
        "ldr r0, _0803D4C4\n\t"
        "_0803D488:\n\t"
        "ldrb r1, [r4]\n\t"
        "ldrb r0, [r0]\n\t"
        "cmp r1, r0\n\t"
        "blo _0803D4D8\n\t"
        "ldr r2, _0803D4C8\n\t"
        "ldr r0, [r2]\n\t"
        "ldr r1, _0803D4CC\n\t"
        "ands r0, r1\n\t"
        "str r0, [r2]\n\t"
        "ldr r3, _0803D4D0\n\t"
        "ldr r2, _0803D4D4\n\t"
        "ldrb r1, [r6]\n\t"
        "movs r0, #0x7f\n\t"
        "ands r0, r1\n\t"
        "lsls r0, r0, #2\n\t"
        "adds r0, r0, r2\n\t"
        "ldr r0, [r0]\n\t"
        "str r0, [r3]\n\t"
        "b _0803D4F0\n\t"
        ".align 2, 0\n\t"
        "_0803D4B0: .4byte gBattleOutcome\n\t"
        "_0803D4B4: .4byte 0x02023D27\n\t"
        "_0803D4B8: .4byte gBattleStruct\n\t"
        "_0803D4BC: .4byte gCurrentTurnActionNumber\n\t"
        "_0803D4C0: .4byte gBattleScriptingCommandsTable\n\t"
        "_0803D4C4: .4byte gBattlersCount\n\t"
        "_0803D4C8: .4byte gHitMarker\n\t"
        "_0803D4CC: .4byte 0xFFEFFFFF\n\t"
        "_0803D4D0: .4byte gBattleMainFunc\n\t"
        "_0803D4D4: .4byte 0x082EC638\n\t"
        "_0803D4D8:\n\t"
        "ldr r0, [r5]\n\t"
        "adds r0, #0x4b\n\t"
        "ldrb r0, [r0]\n\t"
        "cmp r0, r1\n\t"
        "beq _0803D4F0\n\t"
        "ldr r2, _0803D4F8\n\t"
        "ldr r0, [r2]\n\t"
        "ldr r1, _0803D4FC\n\t"
        "ands r0, r1\n\t"
        "ldr r1, _0803D500\n\t"
        "ands r0, r1\n\t"
        "str r0, [r2]\n\t"
        "_0803D4F0:\n\t"
        "pop {r4, r5, r6}\n\t"
        "pop {r0}\n\t"
        "bx r0\n\t"
        ".align 2, 0\n\t"
        "_0803D4F8: .4byte gHitMarker\n\t"
        "_0803D4FC: .4byte 0xFFFFFDFF\n\t"
        "_0803D500: .4byte 0xFFF7FFFF\n\t"
        ".syntax divided\n\t"
    );
}
